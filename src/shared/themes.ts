export function getTerminalTheme(settings: Pick<AppSettings, 'terminalThemeId' | 'customTerminalTheme'>): TerminalTheme {
  if (settings.terminalThemeId === 'custom' && settings.customTerminalTheme) {
    return settings.customTerminalTheme
  }
  return TERMINAL_THEMES.find((theme) => theme.id === settings.terminalThemeId) ?? TERMINAL_THEMES[0]
}

